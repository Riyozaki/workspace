def lint(path):
    lines = open(path, encoding='utf-8').read().split('\n')
    out = []
    for i, ln in enumerate(lines, 1):
        s = ln.strip()
        if not s or s.startswith('#'):
            continue
        # D1: «— Слова. — сказал»
        for m in re.finditer(r"\.\s+—\s+([а-яё]+)", s):
            w = m.group(1)
            if re.match(r"(сказал|спросил|ответил|добавил|повтори|отозвал|согласил|подтверд|заметил|продолж|усмехну|кивну|пожал|буркну|бросил|перебил|подсказ|крикну|поправил|уточнил|прошепт|вздохну|проговори|предлож|велел|пообещ|сообщ|объясн|напомн|возраз|отмахну|засмея|фыркну|хмыкну|поинтерес|осведом|призна|начал|закончил|договори|подума|попроси|переспроси|откликну|шепну|позва|подхват|отреза|обронил|произнёс|выговори|выдохну|протяну|оборва|пробормота|прибавил)", w):
                out.append((i, "D1", "точка перед словами автора → запятая", s[max(0,m.start()-40):m.end()+30]))
        # D2: «, — Сказал»
        for m in re.finditer(r",\s+—\s+([А-ЯЁ][а-яё]+)", s):
            w = m.group(1).lower()
            if re.match(r"(сказал|спросил|ответил|добавил|повтори|отозвал|согласил|подтверд|заметил|продолж|усмехну|кивну|пожал|буркну|бросил|перебил|подсказ|крикну|поправил|уточнил|прошепт|вздохну|проговори|предлож|велел|сообщ|объясн|напомн|возраз|отмахну|засмея|фыркну|хмыкну|поинтерес|призна|начал|закончил|договори|подума|попроси|переспроси|откликну|шепну|позва|подхват|отреза|обронил|произнёс|выговори|выдохну|протяну|оборва|пробормота|прибавил)", w):
                out.append((i, "D2", "заглавная в словах автора после запятой", s[max(0,m.start()-40):m.end()+30]))
        # D3: дефис как тире
        for m in re.finditer(r"\s-\s", s):
            out.append((i, "D3", "дефис вместо тире", s[max(0,m.start()-30):m.end()+30]))
        # C1: нет запятой перед подчинительным союзом
        for m in re.finditer(r"(" + WORD + r")\s+(" + SUBORD + r")\b", s):
            prev, conj = m.group(1), m.group(2)
            pl = prev.lower()
            # исключения: «так что», «потому что» (внутри), «то что» (разг.), «не что иное», «вот что», «мало что», «для того чтобы», «как будто» (сравнение — не всегда), «раз уж», «всё что угодно», союз в начале фразы после тире/скобок
            if conj in ("потому что", "так как") and pl in ("не", "и", "а", "но", "только", "именно", "лишь", "просто", "вот", "разве", "хотя бы"):
                continue
            if conj == "что" and pl in ("потому", "так", "то", "вот", "мало", "всё", "все", "ни", "чуть", "разве", "не", "только", "чего", "ещё", "кое", "как", "едва", "и", "уже", "или", "ли", "-то", "хоть", "почти", "ничего", "нечего", "мало", "хотя", "даже", "а", "но", "ничто", "что", "что-то", "кто", "кто-то"):
                continue
            if conj == "чтобы" and pl in ("того", "не", "для", "только", "лишь", "и", "а", "но", "затем", "именно", "или", "хотя", "чем", "вместо"):
                continue
            if conj in ("если", "когда", "пока", "хотя", "будто", "где", "куда", "откуда", "зачем", "почему", "сколько", "насколько", "словно", "точно", "едва", "поскольку") and pl in ("и", "а", "но", "даже", "или", "только", "лишь", "именно", "вот", "не", "ну", "то", "как", "так", "хоть", "почти", "уже", "ни", "всё", "все", "сразу", "потом", "ровно", "туда", "там", "везде", "оттуда", "отсюда", "здесь", "тут", "чуть", "ещё", "также", "тоже", "вроде", "совсем", "особенно", "ли", "бы", "б", "уж", "неизвестно", "непонятно", "неважно", "мало"):
                continue
            if conj == "точно" or conj == "едва" or conj == "словно":
                continue  # слишком много ложных
            if conj in ("где", "куда", "откуда", "зачем", "почему", "сколько", "насколько") and pl in ("знаю", "знаешь", "знает", "знаем", "знаете", "знают", "знала", "знал", "знали", "понял", "поняла", "понимаю", "понимаешь", "спросил", "спросила", "спрашивал", "спрашивала", "спрашивать", "видно", "ясно", "понятно", "смотря", "решай", "решать", "решить", "думай", "думать", "сказать", "сказал", "сказала", "говорить", "объяснить", "объяснял", "объяснила", "объяснил", "неясно", "непонятно", "неизвестно", "разбирайся"):
                pass  # всё равно кандидат: «не знаю, где» требует запятой
            if conj == "когда" and pl in ("тогда", "того"):
                continue
            if conj == "как будто" or conj == "будто":
                if pl in ("как", "и", "а", "но", "не", "или", "так", "вроде"):
                    continue
            if conj.startswith("котор") and pl in ("тот", "та", "то", "те", "того", "той", "тем", "тех", "из", "в", "на", "с", "о", "у", "к", "по", "за", "под", "над", "при", "про", "без", "от", "до", "для", "через", "перед", "между", "среди", "около", "возле", "против", "сквозь", "вокруг", "мимо", "после", "из-за", "из-под", "и", "а", "но", "или", "не", "каждый", "каждая", "каждое", "каждого", "каждой", "любой", "любая", "любого", "всё", "все", "весь", "вся", "всех", "всего", "всей", "один", "одна", "одно", "одного", "одной"):
                continue
            if pl in ("—", "–"):
                continue
            tail = s[m.end():m.end()+8]
            if re.match(r"-(то|нибудь|либо)\b", tail):
                continue
            if re.match(r"[.!?…]", tail) or re.match(r"\s*[.!?…]", tail):
                continue  # одиночное союзное слово в конце: «не сказал почему»
            if pl in ("за", "обо", "во", "на", "ни", "про", "со", "из-за", "от", "к", "по", "о", "об", "с", "у", "в", "до", "для", "без", "через", "над", "под", "перед", "при", "равно", "мало", "кое", "чуть", "разве", "лишь", "и", "даже", "хоть", "почти", "только", "не", "как", "так", "вот", "то", "потому", "оттого", "всё", "все", "ничего", "нечего", "кто", "что", "ещё", "уже"):
                continue
            if conj == "пока" and re.match(r"\s*(не|ещё|что)\b", s[m.end():]):
                continue
            if conj == "когда" and re.match(r"\s*(-то|-нибудь|угодно)", s[m.end():]):
                continue
            if conj in ("где", "куда", "откуда") and re.match(r"\s*(меньше|больше|лучше|хуже|дальше|ближе|страшнее|важнее|проще|сложнее|интереснее|-то|-нибудь|угодно|надо|положено|следует|попало|придётся)", s[m.end():]):
                continue
            if conj == "сколько" and pl in ("во", "на", "по", "столько", "за"):
                continue
            if conj == "как будто" and pl not in ("такой", "так", "выглядел", "выглядела", "было", "был", "была", "смотрел", "смотрела", "делал", "делала", "говорил", "говорила", "сказал", "сказала", "шёл", "шла"):
                continue
            # союз в начале предложения после точки — регекс требует слова перед ним, значит внутри предложения
            out.append((i, "C1", f"запятая перед «{conj}»?", s[max(0,m.start()-45):m.end()+25]))
        # C2: нет запятой перед «а»/«но»
        for m in re.finditer(r"(" + WORD + r")\s+(а|но)\s+(" + WORD + r")", s):
            pl = m.group(1).lower(); nx = m.group(3).lower()
            if pl in ("не", "и", "или", "то", "ну", "да", "ведь", "-то", "вот", "как", "так", "уж", "нет", "что") and m.group(2) == "а":
                if pl not in ("не",):  # «не X а Y» — тоже ошибка, но «то а» редко
                    continue
            if m.group(2) == "а" and pl in ("и", "или", "то", "ну", "да", "ведь", "вот", "как", "так", "уж", "нет", "ага", "что", "чего", "-то", "-ка"):
                continue
            if m.group(2) == "но" and pl in ("и", "или", "да", "ну", "-то", "то", "не"):
                continue
            if nx in ("не", "то", "ведь", "именно") and m.group(2) == "а" and pl in ("не",):
                pass
            out.append((i, "C2", f"запятая перед «{m.group(2)}»?", s[max(0,m.start()-40):m.end()+25]))
        # C3: сравнительная + чем без запятой
        for m in re.finditer(r"([А-Яа-яё\-]+(ее|ей|ше|же|ьше|ольше|еньше))\s+чем\s", s):
            if m.group(1).lower() in ("более", "менее", "не более", "не менее", "больше", "меньше") and False:
                continue
            out.append((i, "C3", "запятая перед «чем»?", s[max(0,m.start()-40):m.end()+30]))
        for m in re.finditer(r"\b(больше|меньше|дольше|раньше|позже|лучше|хуже|выше|ниже|дальше|ближе|скорее|проще|сложнее|тише|громче|быстрее|медленнее|чаще|реже|иначе|иных|другой|другая|другое|другого|другие|других|иное|иначе)\s+чем\s", s, re.I):
            out.append((i, "C3", "запятая перед «чем»?", s[max(0,m.start()-40):m.end()+30]))
        # C4: вводные без запятых
        for w in INTRO:
            for m in re.finditer(r"(^|[^А-Яа-яЁё\-])" + re.escape(w) + r"($|[^А-Яа-яЁё\-])", s, re.I):
                a = m.start() + len(m.group(1)); b = m.end() - len(m.group(2))
                before = s[:a].rstrip(); after = s[b:].lstrip()
                if w == "правда" and not (before.endswith(('—', ',')) or after.startswith(',')):
                    # «правда» часто существительное
                    continue
                if w == "конечно" and False:
                    continue
                if w in ("может быть",) and re.match(r"(^|.*\s)(не|это|оно|он|она|там|что|кто|как|где|и|а|но|или|которая|который|такое|такой|только)$", before.lower()):
                    if not after.startswith((',', '.', '?', '!')):
                        pass
                ok_before = (before == '' or before.endswith((',', '—', '–', '(', '«', ':', ';', '.', '!', '?', '…')))
                ok_after = (after == '' or after.startswith((',', '.', '!', '?', '…', ':', ';', '—', '»', ')')))
                if not (ok_before and ok_after):
                    if w == "может быть" and re.search(r"(не|это|там|тут|здесь|и|а|но|или|что|кто|как|где|только|оно|он|она|мне|тебе|ему|ей|нам|им)\s*$", before.lower()) and re.match(r"(и|а|но|что|кто|как|где|всё|все|так|только|мало|много|больше|меньше|хуже|лучше|иначе|разн|один|два|три|четыр|пят|сорок|сто)", after.lower()):
                        continue  # «может быть больше/иначе» — сказуемое
                    if w == "конечно" and re.match(r"(же|нет|да)\b", after.lower()):
                        pass
                    out.append((i, "C4", f"вводное «{w}» без запятых?", s[max(0,a-35):b+35]))
        # O1: орфография
        for pat, rep in ORTHO:
            if rep == "✓":
                continue
            for m in re.finditer(pat, s, re.I):
                if rep.endswith("✓") or rep.endswith("✓ (через дефис)"):
                    continue
                out.append((i, "O1", f"«{m.group(0)}» → {rep}", s[max(0,m.start()-30):m.end()+30]))
        # O2: так же/также, то же/тоже
        for m in re.finditer(r"\bтак же\b", s):
            after = s[m.end():m.end()+12].lstrip()
            if not re.match(r"(,|как|—|и\b|\.|$|как|в |при|по|на |к |с |у |о |же|молча|тихо|громко|коротко|крепко|ровно|быстро|медленно|плохо|хорошо|ты|он|она|они|мы|я |спокойно|внимательно|близко|далеко|дословно|точно|осторожно|легко|неохотно|редко|часто|ничего|никак|неподвижно|честно|без|одинаково|негромко|мало|много|не )", after):
                out.append((i, "O2", "«так же» — не «также»?", s[max(0,m.start()-35):m.end()+35]))
        for m in re.finditer(r"\bто же\b", s):
            after = s[m.end():m.end()+10].lstrip()
            if not re.match(r"(самое|,|—|\.|!|\?|что|место|время|лицо|слово|дело|окно|имя|движение|чувство|настроение|молчание|выражение|$|:)", after):
                out.append((i, "O2", "«то же» — не «тоже»?", s[max(0,m.start()-35):m.end()+35]))
        # S1: пробелы
        if "  " in s:
            out.append((i, "S1", "двойной пробел", s[max(0,s.find("  ")-30):s.find("  ")+30]))
        for m in re.finditer(r"\s[,.!?;:]", s):
            if s[m.start()-1:m.start()] in ("—", "–") or s[m.start()+1:m.start()+4] == "...":
                continue
            out.append((i, "S1", "пробел перед знаком", s[max(0,m.start()-30):m.end()+30]))
        for m in re.finditer(r"[,.!?;:][А-Яа-яЁё]", s):
            if re.match(r"\.\.", s[m.start():m.start()+2]):
                continue
            out.append((i, "S1", "нет пробела после знака", s[max(0,m.start()-30):m.end()+30]))
    return out

def main():
    paths = [a for a in sys.argv[1:] if not a.startswith('--')]
    for p in paths:
        res = lint(p)
        print(f"=== {p}: {len(res)} кандидатов ===")
        for i, code, msg, ctx in res:
            print(f"[{code}] {i}: {msg}\n      …{ctx}…")

if __name__ == '__main__':
    main()

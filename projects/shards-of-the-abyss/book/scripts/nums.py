import re,sys
NUM=r"(?:\d+|одиннадцат\w*|двенадцат\w*|тринадцат\w*|четырнадцат\w*|пятнадцат\w*|шестнадцат\w*|семнадцат\w*|восемнадцат\w*|девятнадцат\w*|двадцат\w*|тридцат\w*|сорок\w*|пятьдесят|пятидесят\w*|шестьдесят|шестидесят\w*|семьдесят|восемьдесят|девяност\w*|сто|ста|сот\w*|двести|двухсот|триста|трёхсот|четыреста|пятьсот|шестьсот|тысяч\w*|полтор\w*|дв[аеу]х?|двум\w*|тр[иёе]х?|трём\w*|четыр\w*|пят[ьи]|шест[ьи]|сем[ьи]|восем\w*|восьм\w*|девят\w*|десят\w*|дюжин\w*)"
UNIT=r"(?:минут\w*|секунд\w*|шаг\w*|лет|год\w*|дн[еяй]\w*|сут\w*|локт\w*|ладон\w*|пальц\w*|раз\w*|человек\w*|ступен\w*|колокол\w*|декад\w*|месяц\w*|зим\w*|сезон\w*)"
pat=re.compile(rf"\b{NUM}(?:\s+{NUM})?(?:\s+(?:с\s+\w+|или\s+{NUM}|-{NUM}))?\s+{UNIT}\b|\b{UNIT}\s+(?:{NUM}\s*)+\b|\b(?:минут\w*|секунд\w*|шагов)\s+{NUM}\b|\bполсекунд\w*|\bполминут\w*|\bполколокола|\bполуколокол\w*|\bиз\s+{NUM}\b|\b{NUM}\s+из\s+{NUM}",re.I)
for p in sys.argv[1:]:
    lines=open(p,encoding='utf-8').read().split('\n'); c=0
    for i,l in enumerate(lines,1):
        ms=list(pat.finditer(l))
        if ms:
            c+=len(ms)
            print(f"{i}: "+" | ".join(l[max(0,m.start()-60):m.end()+40].replace('\n',' ') for m in ms))
    print(f"### {p}: {c}")

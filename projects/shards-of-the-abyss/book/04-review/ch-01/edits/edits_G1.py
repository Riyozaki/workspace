def rep(old,new):
    global t,n
    assert t.count(old)==1,(t.count(old),old[:80]); t=t.replace(old,new); n+=1
def cut(a,b,new):
    """заменить от начала a до конца b включительно"""
    global t,n
    i=t.index(a); j=t.index(b,i)+len(b)
    assert t.count(a)==1 and t.count(b)==1
    t=t[:i]+new+t[j:]; n+=1


# -*- coding: utf-8 -*-

with open("chapter_11.md", "r", encoding="utf-8") as f:
    text = f.read()

# 1. стереоскопической
text = text.replace("стереоскопической глубины", "живой пространственной глубины")

# 2. гироскопическим
text = text.replace("с контролируемым гироскопическим вращением", "с выверенным винтовым вращением")

# 3. эллипсоид инерции
text = text.replace("асимметричный эллипсоид инерции неизбежно заваливал кубики", "смещенный центр тяжести неизбежно заваливал кости")

# 4. центробежная сила
text = text.replace("центробежная сила прижимает тяжелую грань к стенке", "вращение прижимает тяжелую грань к стенке")

# 5. Центробежное смещение эндолимфы
text = text.replace("Центробежное смещение эндолимфы при угловом ускорении.", "Смещение жидкости во внутреннем ухе при резком повороте головы.")

# 6. яростно прикусив
text = text.replace("яростно прикусив губу до крови", "до боли прикусив губу")

# 7. пять лет могильного бесчувствия
text = text.replace("Пять лет могильного бесчувствия", "Два года могильного бесчувствия")

# 8. семьдесят восемь суток -> пятьдесят суток
text = text.replace("семьдесят восемь суток", "пятьдесят суток")

with open("chapter_11.md", "w", encoding="utf-8") as f:
    f.write(text)

print("Updated ch11.")

# -*- coding: utf-8 -*-

with open("chapter_9.md", "r", encoding="utf-8") as f:
    text = f.read()

# 1. петрикор
text = text.replace("Это был петрикор.", "Это был первозданный запах земли, который бывает лишь перед очистительной горной грозой.")

# 2. геосмин
text = text.replace("Молекулы геосмина, рожденные почвенными бактериями в пересохших расщелинах, жадно соединялись с первыми микроскопическими каплями небесной влаги, поднимаясь в нагретый воздух невидимой ароматной волной.", 
                    "Дыхание сухой глины и прелых трав, дремавших под слоем щебня, жадно соединялось с первыми каплями небесной влаги, поднимаясь в нагретый воздух терпкой, пьянящей волной.")

# 3. барометрическое давление
text = text.replace("Барометрическое давление упало с пугающей внезапностью: воздух резко остыл", 
                    "Воздух резко остыл и потяжелел, словно перед самым началом сокрушительного обвала")

# 4. десять лет -> полтора десятка лет
text = text.replace("Только на десять лет раньше тебя.", "Только на полтора десятка лет раньше тебя.")

# 5. таймер девяти декад -> шести декад
text = text.replace("До праздника Жовтня остается менее девяти декад", "До праздника Жовтня остается менее шести декад")

# 6. пять лет -> два года
text = text.replace("Обонятельные рецепторы, спавшие пять лет под непроницаемой броней контракта, не просто вернулись к работе", 
                    "Обоняние, спавшее два года под непроницаемой броней контракта, вернулось к жизни")
text = text.replace("впервые за пять лет вдыхал аромат живой земли.", "впервые за два года вдыхал аромат живой земли.")

with open("chapter_9.md", "w", encoding="utf-8") as f:
    f.write(text)


# -*- coding: utf-8 -*-

with open("chapter_13.md", "r", encoding="utf-8") as f:
    text = f.read()

t = "— Нужно, — спокойно ответил Лукас. — Лошадь ждет в распадке у ручья. Дорогу подсушит к полудню."
r = """— Нужно, — спокойно ответил Лукас. — Лошадь ждет в распадке у ручья. Дорогу подсушит к полудню.

Он достал из сумки чистую полотняную ленту и бережно перевязал ее ссаженную ладонь, смочив ткань легким настоем календулы. Девушка терпела прикосновение без звука, глядя, как первые лучи солнца озаряют базальтовые кручи. В утреннем свете гранитные пики казались высеченными из розового кварца, а свежий горный ветер разгонял остатки ночного ненастья над ущельем."""

assert t in text
text = text.replace(t, r, 1)

with open("chapter_13.md", "w", encoding="utf-8") as f:
    f.write(text)


# -*- coding: utf-8 -*-

with open("chapter_12.md", "r", encoding="utf-8") as f:
    text = f.read()

# 1. пятилетнее онемение -> двухлетнее
text = text.replace("сквозь пятилетнее онемение", "сквозь двухлетнее онемение")

# 2. пять долгих лет после гибели Эмили -> два долгих года
text = text.replace("пять долгих лет после гибели Эмили", "два долгих года после гибели Эмили")

# 3. пять лет назад, глядя на свои окровавленные руки -> два года назад
text = text.replace("пять лет назад, глядя на свои окровавленные руки", "два года назад, глядя на свои окровавленные руки")

# 4. Впервые за долгие годы -> ок

# 5. Fix contrast pattern:
old_c = "Это не было соматическим спазмом уставших нервов. Это был дикий, нестерпимый страх за чужую жизнь, заставивший его сердце заколотиться в ребра с удвоенной силой."
new_c = "В груди лекаря забился дикий, нестерпимый страх за чужую жизнь: сердце колотилось в ребра с удвоенной силой, пробивая гранитную скорлупу бесчувствия."
assert old_c in text
text = text.replace(old_c, new_c, 1)

# Strip trailing whitespace on each line
lines = [l.rstrip() for l in text.splitlines()]
text = "\n".join(lines) + "\n"

with open("chapter_12.md", "w", encoding="utf-8") as f:
    f.write(text)

print("Updated ch12.")

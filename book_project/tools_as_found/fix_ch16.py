# -*- coding: utf-8 -*-

with open("chapter_16.md", "r", encoding="utf-8") as f:
    text = f.read()

# 1. 5 years -> 2 years
text = text.replace("Ты сам пришел на перекресток пять лет назад, Лукас.", "Ты сам пришел на перекресток два года назад, Лукас.")
text = text.replace("гибель Эмили на операционном столе, казнь Юлиана на площади, пять лет глухого оцепенения — сжалась в одну ослепительную точку.", "гибель Эмили на операционном столе, искалеченная судьба Юлиана, два года глухого оцепенения — сжались в одну ослепительную точку.")
text = text.replace("Этерий, дремавший пять лет под спудом договора", "Этерий, дремавший два года под спудом договора")
text = text.replace("которую пять лет берег в добровольном оцепенении", "которую два года берег в добровольном оцепенении")

# Strip trailing whitespaces:
lines = [l.rstrip() for l in text.splitlines()]
text = "\n".join(lines) + "\n"

with open("chapter_16.md", "w", encoding="utf-8") as f:
    f.write(text)

print("Updated ch16.")

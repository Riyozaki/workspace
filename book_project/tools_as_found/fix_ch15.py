# -*- coding: utf-8 -*-

with open("chapter_15.md", "r", encoding="utf-8") as f:
    text = f.read()

# 1. венецианскими
text = text.replace("венецианскими зеркалами", "южными гильдейскими зеркалами")

# 2. пять лет
text = text.replace("замороженные пять лет назад сделкой с Орхастом", "замороженные два года назад сделкой с Орхастом")
text = text.replace("в котором пять лет покоились его хирургические скальпели и серебряные иглы Юлиана", "в котором два года покоились его хирургические скальпели и серебряные иглы из столичного госпиталя")
text = text.replace("Впервые за пять лет его душа не застывала", "Впервые за два года его душа не застывала")
text = text.replace("Пять лет лекарь считал себя мертвым камнем", "Два года лекарь считал себя мертвым камнем")

# 3. яростн
text = text.replace("Горм яростно обернулся к Лукасу", "Горм резко обернулся к Лукасу")
text = text.replace("Девушка отбивалась яростно, как дикая рысь", "Девушка отбивалась отчаянно, как пойманная рысь")
text = text.replace("бушевало незнакомое, яростное пламя", "бушевало незнакомое, грозное пламя")

# Strip trailing whitespaces:
lines = [l.rstrip() for l in text.splitlines()]
text = "\n".join(lines) + "\n"

with open("chapter_15.md", "w", encoding="utf-8") as f:
    f.write(text)

print("Updated ch15.")
